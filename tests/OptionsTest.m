classdef OptionsTest < RestTestCase
    %OPTIONSTEST Option methods: optional fields, deprecation warnings and
    %   the typed option legs.

    methods (Test)
        function optiongreeksOptionalFields(tc)
            tc.Client.optiongreeks(symbol="NIFTY02DEC2526000CE", exchange="NFO", interest_rate=6.5, ...
                forward_price=26350, expiry_time="15:30");
            tc.verifySinglePost('optiongreeks', ['{"apikey":"test-api-key","symbol":"NIFTY02DEC2526000CE",' ...
                '"exchange":"NFO","interest_rate":6.5,"forward_price":26350,"expiry_time":"15:30"}']);
            tc.Server.reset();
            tc.Client.optiongreeks(symbol="X", exchange="NFO", underlying_symbol="NIFTY30DEC25FUT", ...
                underlying_exchange="NFO");
            tc.verifySinglePost('optiongreeks', ['{"apikey":"test-api-key","symbol":"X","exchange":"NFO",' ...
                '"underlying_symbol":"NIFTY30DEC25FUT","underlying_exchange":"NFO"}']);
        end

        function optionsorderDefaults(tc)
            tc.verifyWarningFree(@() tc.Client.optionsorder(underlying="NIFTY", exchange="NSE_INDEX", ...
                expiry_date="28NOV24", offset="ATM", option_type="CE", action="BUY", quantity=75));
            tc.verifySinglePost('optionsorder', ['{"apikey":"test-api-key","strategy":"Python",' ...
                '"underlying":"NIFTY","exchange":"NSE_INDEX","offset":"ATM","option_type":"CE",' ...
                '"action":"BUY","quantity":"75","pricetype":"MARKET","product":"MIS",' ...
                '"expiry_date":"28NOV24"}']);
        end

        function optionsorderStrikeIntIsDeprecated(tc)
            tc.verifyWarning(@() tc.Client.optionsorder(strategy="s", underlying="NIFTY", ...
                exchange="NSE_INDEX", strike_int=50, offset="OTM1", option_type="CE", action="BUY", ...
                quantity=75, price_type="LIMIT", product="NRML", price="50.0", trigger_price=49.5), ...
                'openalgo:deprecated');
            tc.verifySinglePost('optionsorder', ['{"apikey":"test-api-key","strategy":"s",' ...
                '"underlying":"NIFTY","exchange":"NSE_INDEX","offset":"OTM1","option_type":"CE",' ...
                '"action":"BUY","quantity":"75","pricetype":"LIMIT","product":"NRML",' ...
                '"strike_int":"50","price":"50.0","trigger_price":"49.5"}']);
            c = tc.Client;
            [msg, id] = RestTestCase.lastWarningOf(@() c.optionsorder(underlying="NIFTY", ...
                exchange="NSE_INDEX", strike_int=50, offset="ATM", option_type="CE", action="BUY", ...
                quantity=1));
            tc.verifyEqual(id, 'openalgo:deprecated');
            tc.verifyEqual(msg, ...
                'The ''strike_int'' parameter is deprecated and will be removed in future versions.');
        end

        function optionsymbolDeprecations(tc)
            import matlab.unittest.constraints.IssuesWarnings
            c = tc.Client;
            % strategy and strike_int each raise their own deprecation warning
            tc.verifyThat(@() c.optionsymbol(strategy="t", underlying="NIFTY", exchange="NSE_INDEX", ...
                expiry_date="28OCT25", strike_int=50, offset="ATM", option_type="CE", n=1), ...
                IssuesWarnings({'openalgo:deprecated', 'openalgo:deprecated'}, ...
                'RespectingCount', true, 'Exactly', true));
            tc.verifySinglePost('optionsymbol', ['{"apikey":"test-api-key","underlying":"NIFTY",' ...
                '"exchange":"NSE_INDEX","offset":"ATM","option_type":"CE","strategy":"t",' ...
                '"strike_int":"50","expiry_date":"28OCT25","n":"1"}']);
            [msg, id] = RestTestCase.lastWarningOf(@() c.optionsymbol(strategy="t", ...
                underlying="NIFTY", exchange="NSE_INDEX", offset="ATM", option_type="CE"));
            tc.verifyEqual(id, 'openalgo:deprecated');
            tc.verifyEqual(msg, ...
                'The ''strategy'' parameter is deprecated and will be removed in future versions.');
            tc.Server.reset();
            tc.verifyWarningFree(@() c.optionsymbol(underlying="NIFTY28OCT25FUT", ...
                exchange="NFO", offset="ITM2", option_type="PE"));
            tc.verifySinglePost('optionsymbol', ['{"apikey":"test-api-key","underlying":"NIFTY28OCT25FUT",' ...
                '"exchange":"NFO","offset":"ITM2","option_type":"PE"}']);
        end

        function optionsmultiorderLegs(tc)
            legs = {struct('offset', 'OTM10', 'option_type', 'CE', 'action', 'BUY', 'quantity', 75), ...
                    struct('offset', 'OTM5', 'option_type', 'PE', 'action', 'SELL', 'quantity', '75', ...
                        'expiry_date', '02DEC25', 'pricetype', 'LIMIT', 'product', 'NRML', 'price', 50, ...
                        'trigger_price', '49.5', 'disclosed_quantity', '0')};
            tc.Client.optionsmultiorder(strategy="Iron Condor", underlying="NIFTY", exchange="NSE_INDEX", ...
                expiry_date="25NOV25", legs=legs, tag=1);
            tc.verifySinglePost('optionsmultiorder', ['{"apikey":"test-api-key","strategy":"Iron Condor",' ...
                '"underlying":"NIFTY","exchange":"NSE_INDEX","legs":[{"offset":"OTM10","option_type":"CE",' ...
                '"action":"BUY","quantity":75},{"offset":"OTM5","option_type":"PE","action":"SELL",' ...
                '"quantity":75,"expiry_date":"02DEC25","pricetype":"LIMIT","product":"NRML",' ...
                '"price":50.0,"trigger_price":49.5,"disclosed_quantity":0}],"expiry_date":"25NOV25","tag":1}']);
        end

        function optionsmultiorderOneLegAndStrikeInt(tc)
            leg = struct('offset', 'ATM', 'option_type', 'CE', 'action', 'BUY', 'quantity', 75.9);
            tc.verifyWarning(@() tc.Client.optionsmultiorder(strategy="s", underlying="NIFTY", ...
                exchange="NSE_INDEX", strike_int="50", legs=leg), 'openalgo:deprecated');
            tc.verifySinglePost('optionsmultiorder', ['{"apikey":"test-api-key","strategy":"s",' ...
                '"underlying":"NIFTY","exchange":"NSE_INDEX","legs":[{"offset":"ATM","option_type":"CE",' ...
                '"action":"BUY","quantity":75}],"strike_int":50}']);
        end

        function optionsmultiorderErrors(tc)
            c = tc.Client;
            bad = struct('offset', 'ATM', 'option_type', 'CE', 'quantity', 75);
            tc.verifyError(@() c.optionsmultiorder(strategy="s", underlying="NIFTY", ...
                exchange="NSE_INDEX", legs={bad}), 'openalgo:keyError');   % Python KeyError 'action'
            tc.verifyError(@() c.optionsmultiorder(underlying="NIFTY", exchange="NSE_INDEX", ...
                legs={}), 'openalgo:missingArgument');                    % strategy is required
            tc.verifyError(@() c.optionsmultiorder(strategy="s", underlying="NIFTY", ...
                exchange="NSE_INDEX", legs=[]), 'openalgo:typeError');
            leg = struct('offset', 'ATM', 'option_type', 'CE', 'action', 'BUY', 'quantity', 'many');
            tc.verifyError(@() c.optionsmultiorder(strategy="s", underlying="NIFTY", ...
                exchange="NSE_INDEX", legs={leg}), 'openalgo:valueError');
            tc.verifyNoRequest();
        end

        function optionchain(tc)
            tc.Client.optionchain(underlying="NIFTY", exchange="NSE_INDEX", expiry_date="30DEC25", ...
                strike_count="10");
            tc.verifySinglePost('optionchain', ['{"apikey":"test-api-key","underlying":"NIFTY",' ...
                '"exchange":"NSE_INDEX","expiry_date":"30DEC25","strike_count":10}']);
            tc.Server.reset();
            tc.Client.optionchain(underlying="NIFTY", exchange="NSE_INDEX");
            tc.verifySinglePost('optionchain', '{"apikey":"test-api-key","underlying":"NIFTY","exchange":"NSE_INDEX"}');
        end
    end
end
